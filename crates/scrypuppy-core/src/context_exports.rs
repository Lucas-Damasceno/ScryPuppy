//! Encrypted Markdown exports for user-created contexts.
//!
//! The file format is shared with the Tauri app so exports remain portable
//! across the UI migration.
use std::{fs, io::Write, path::Path};

use rusqlite::Connection;

use crate::{
    crypto::encrypt_context_file,
    library::{capture_base_from_row, hydrate_captures, CaptureDto, ContextDto},
};

fn err(error: impl ToString) -> String {
    error.to_string()
}

pub fn list_contexts(conn: &Connection) -> rusqlite::Result<Vec<ContextDto>> {
    let mut stmt = conn.prepare(
        "SELECT co.id, co.name, co.normalized_name, co.slug, co.created_at, co.updated_at,
                COUNT(cc.capture_id) AS capture_count
         FROM contexts co
         LEFT JOIN capture_contexts cc ON cc.context_id = co.id
         WHERE co.id NOT IN ('inbox', 'knowledge-base')
         GROUP BY co.id
         ORDER BY lower(co.name)",
    )?;
    let contexts = stmt
        .query_map([], |row| {
            Ok(ContextDto {
                id: row.get(0)?,
                name: row.get(1)?,
                normalized_name: row.get(2)?,
                slug: row.get(3)?,
                created_at: row.get(4)?,
                updated_at: row.get(5)?,
                capture_count: row.get(6)?,
            })
        })?
        .collect();
    contexts
}

pub fn captures_for_context(
    conn: &Connection,
    context_id: &str,
) -> Result<Vec<CaptureDto>, String> {
    let mut stmt = conn
        .prepare(
            "SELECT c.id, c.content_text, c.captured_at,
                c.source_app_name, c.source_app_id, c.source_process_id,
                c.source_process_path, c.window_title, c.window_id, c.platform,
                c.metadata_json, c.capture_kind
         FROM captures c JOIN capture_contexts cc ON cc.capture_id = c.id
         WHERE cc.context_id = ? ORDER BY c.captured_at DESC",
        )
        .map_err(err)?;
    let mut captures = stmt
        .query_map([context_id], capture_base_from_row)
        .map_err(err)?
        .collect::<rusqlite::Result<Vec<_>>>()
        .map_err(err)?;
    hydrate_captures(conn, &mut captures)?;
    Ok(captures)
}

pub fn render_context_markdown(context: &ContextDto, captures: &[CaptureDto]) -> String {
    let mut markdown = String::new();
    markdown.push_str(
        "<!-- Generated by ScryPuppy. Do not edit manually; changes can be overwritten. -->\n\n",
    );
    markdown.push_str(&format!("# {}\n\n", context.name));
    markdown.push_str(&format!("- Context ID: `{}`\n", context.id));
    markdown.push_str(&format!("- Captures: `{}`\n\n", captures.len()));
    for capture in captures {
        markdown.push_str("---\n\n");
        markdown.push_str(&format!("## {}\n\n", capture.captured_at));
        markdown.push_str(&format!("- Capture ID: `{}`\n", capture.id));
        markdown.push_str(&format!("- Type: `{}`\n", capture.kind));
        if !capture.contexts.is_empty() {
            markdown.push_str(&format!(
                "- Contexts: `{}`\n",
                capture
                    .contexts
                    .iter()
                    .map(|c| c.name.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        markdown.push_str(&format!(
            "- Application: `{}`\n",
            optional_md(&capture.source_app_name)
        ));
        markdown.push_str(&format!(
            "- Application ID: `{}`\n",
            optional_md(&capture.source_app_id)
        ));
        markdown.push_str(&format!(
            "- Process ID: `{}`\n",
            capture
                .source_process_id
                .map(|pid| pid.to_string())
                .unwrap_or_else(|| "unknown".into())
        ));
        markdown.push_str(&format!(
            "- Process Path: `{}`\n",
            optional_md(&capture.source_process_path)
        ));
        markdown.push_str(&format!(
            "- Window Title: `{}`\n",
            optional_md(&capture.window_title)
        ));
        markdown.push_str(&format!(
            "- Window ID: `{}`\n",
            optional_md(&capture.window_id)
        ));
        markdown.push_str(&format!("- Platform: `{}`\n", capture.platform));
        for asset in &capture.assets {
            markdown.push_str(&format!(
                "- Asset {}: status `{}`, path `{}`{}\n",
                asset.kind,
                asset.status,
                optional_md(&asset.path),
                asset
                    .error
                    .as_ref()
                    .map(|e| format!(", error `{}`", escape_ticks(e)))
                    .unwrap_or_default()
            ));
        }
        if !capture.tags.is_empty() {
            markdown.push_str(&format!("- Tags: `{}`\n", capture.tags.join("`, `")));
        }
        if let Some(ocr) = &capture.ocr {
            markdown.push_str(&format!("- OCR local: `{}`", ocr.status));
            if let Some(error) = &ocr.error {
                markdown.push_str(&format!(" ({})", escape_ticks(error)));
            }
            markdown.push('\n');
        }
        markdown.push_str("\n```text\n");
        markdown.push_str(&capture.content_text);
        if !capture.content_text.ends_with('\n') {
            markdown.push('\n');
        }
        markdown.push_str("```\n\n<details>\n<summary>Metadata JSON</summary>\n\n```json\n");
        markdown.push_str(
            &serde_json::to_string_pretty(&capture.metadata).unwrap_or_else(|_| "{}".into()),
        );
        markdown.push_str("\n```\n</details>\n\n");
        if !capture.entities.is_empty() {
            markdown.push_str("<details>\n<summary>Local Entities</summary>\n\n");
            for entity in &capture.entities {
                markdown.push_str(&format!(
                    "- `{}`: `{}` (source `{}`, confidence `{:.2}`)\n",
                    entity.kind,
                    escape_ticks(&entity.value),
                    entity.source,
                    entity.confidence
                ));
            }
            markdown.push_str("\n</details>\n\n");
        }
    }
    markdown
}

fn optional_md(value: &Option<String>) -> String {
    value
        .as_ref()
        .map(|v| escape_ticks(v))
        .unwrap_or_else(|| "unknown".into())
}
fn escape_ticks(value: &str) -> String {
    value.replace('`', "'")
}

/// Write a context export using the existing encrypted format and safe replace sequence.
pub fn write_context_export(
    conn: &Connection,
    directory: &Path,
    context: &ContextDto,
    key: &str,
) -> std::io::Result<()> {
    let captures = captures_for_context(conn, &context.id).map_err(io_other)?;
    let markdown = render_context_markdown(context, &captures);
    let encrypted = encrypt_context_file(&markdown, key).map_err(io_other)?;
    let path = directory.join(format!("{}.scryppy", context.slug));
    let temporary = directory.join(format!(".{}.{}.tmp", context.slug, uuid::Uuid::new_v4()));
    fs::write(&temporary, encrypted)?;
    if path.exists() {
        secure_remove_file(&path).map_err(io_other)?;
    }
    fs::rename(temporary, path)
}

pub fn secure_remove_file(path: &Path) -> Result<(), String> {
    if !path.exists() {
        return Ok(());
    }
    if path.is_file() {
        let len = fs::metadata(path).map_err(err)?.len();
        let mut file = fs::OpenOptions::new().write(true).open(path).map_err(err)?;
        let zeros = [0u8; 8192];
        let mut remaining = len;
        while remaining > 0 {
            let amount = remaining.min(zeros.len() as u64) as usize;
            file.write_all(&zeros[..amount]).map_err(err)?;
            remaining -= amount as u64;
        }
        file.sync_all().map_err(err)?;
    }
    fs::remove_file(path).map_err(err)
}

fn io_other(error: impl ToString) -> std::io::Error {
    std::io::Error::other(error.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::crypto::CONTEXT_FILE_MAGIC;

    #[test]
    fn context_export_keeps_encrypted_file_format_and_secure_delete() {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(
            "CREATE TABLE captures (
                id TEXT PRIMARY KEY, content_text TEXT, captured_at TEXT,
                source_app_name TEXT, source_app_id TEXT, source_process_id INTEGER,
                source_process_path TEXT, window_title TEXT, window_id TEXT,
                platform TEXT, metadata_json TEXT, capture_kind TEXT
            );
            CREATE TABLE capture_contexts (capture_id TEXT, context_id TEXT);",
        )
        .unwrap();
        let dir = tempfile::tempdir().unwrap();
        let context = ContextDto {
            id: "ctx-1".into(),
            name: "Confidencial".into(),
            normalized_name: "confidencial".into(),
            slug: "confidencial".into(),
            created_at: "now".into(),
            updated_at: "now".into(),
            capture_count: 0,
        };
        let key = "11".repeat(32);

        write_context_export(&conn, dir.path(), &context, &key).unwrap();
        let path = dir.path().join("confidencial.scryppy");
        let bytes = fs::read(&path).unwrap();
        assert!(bytes.starts_with(CONTEXT_FILE_MAGIC));
        assert!(!bytes
            .windows("Confidencial".len())
            .any(|window| window == b"Confidencial"));

        secure_remove_file(&path).unwrap();
        assert!(!path.exists());
    }
}
